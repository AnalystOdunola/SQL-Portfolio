--35. CUSTOMERS PURCHASE FREQUENCY--

SELECT
    c.CustomerName,
    COUNT(DISTINCT o.OrderNumber) AS NumberOfOrders,
    SUM(od.Sales) AS TotalSpent
FROM Customers c
INNER JOIN Orders o
    ON o.CustomerID = c.CustomerID
INNER JOIN OrderDetails od
    ON od.OrderNumber = o.OrderNumber
GROUP BY
    c.CustomerID,
    c.CustomerName
ORDER BY NumberOfOrders DESC;


--36. REVENUE GENERATED BY DEAL SIZE--

SELECT
    od.DealSize,
    COUNT(*) AS TotalOrders,
    SUM(od.Sales) AS TotalRevenue,
    AVG(od.Sales) AS AverageRevenue
FROM OrderDetails od
GROUP BY od.DealSize
ORDER BY TotalRevenue DESC;


--37. TOP CUSTOMERS PER COUNTRY--

WITH CustomerRevenue AS
(
    SELECT
        c.Country,
        c.CustomerName,
        SUM(od.Sales) AS TotalSpent,

        ROW_NUMBER() OVER
        (
            PARTITION BY c.Country
            ORDER BY SUM(od.Sales) DESC
        ) AS rn

    FROM Customers c
    INNER JOIN Orders o
        ON o.CustomerID = c.CustomerID
    INNER JOIN OrderDetails od
        ON od.OrderNumber = o.OrderNumber
         GROUP BY
        c.Country,
        c.CustomerName
)

SELECT
    Country,
    CustomerName,
    TotalSpent
FROM CustomerRevenue
WHERE rn <= 3
ORDER BY
    Country,
    TotalSpent DESC;



--13. PRODUCTS WITH MSRP GREATER THAN 100--


SELECT
    ProductCode,
    ProductLine,
    MSRP
FROM Products
WHERE MSRP > 100
ORDER BY MSRP DESC;



--14. CUSTOMERS WITH MORE THAN 5 ORDERS--


SELECT
    c.CustomerName,
    COUNT(o.OrderNumber) AS TotalOrders
FROM Customers c
JOIN Orders o
    ON c.CustomerID = o.CustomerID
GROUP BY c.CustomerName
HAVING COUNT(o.OrderNumber) > 5
ORDER BY TotalOrders DESC;



--15. CUSTOMERS WITH THEIR ORDERS--


SELECT
    c.CustomerID,
    c.CustomerName,
    o.OrderNumber,
    o.OrderDate,
    o.Status
FROM Customers c
INNER JOIN Orders o
    ON c.CustomerID = o.CustomerID
ORDER BY o.OrderDate;



--16. PRODUCTS WITH SALES DETAILS--

SELECT
    p.ProductCode,
    p.ProductLine,
    od.OrderNumber,
    od.QuantityOrdered,
    od.Sales
FROM Products p
INNER JOIN OrderDetails od
    ON p.ProductCode = od.ProductCode
ORDER BY od.Sales DESC;



--17. ALL CUSTOMERS INCLUDING THOSE WITHOUT ORDERS--


SELECT
    c.CustomerID,
    c.CustomerName,
    o.OrderNumber,
    o.Status
FROM Customers c
LEFT JOIN Orders o
    ON c.CustomerID = o.CustomerID
ORDER BY c.CustomerName;



--18. PRODUCTS WITHOUT SALES--


SELECT
    p.ProductCode,
    p.ProductLine
FROM Products p
LEFT JOIN OrderDetails od
    ON p.ProductCode = od.ProductCode
WHERE od.ProductCode IS NULL
ORDER BY p.ProductCode;



--19. ALL ORDERS INCLUDING MISSING CUSTOMER RECORDS--

SELECT
    c.CustomerName,
    o.OrderNumber,
    o.OrderDate,
    o.Status
FROM Customers c
RIGHT JOIN Orders o
    ON c.CustomerID = o.CustomerID
ORDER BY o.OrderDate;



--20. CUSTOMERS WITH ABOVE-AVERAGE SALES--

SELECT
    CustomerName,
    TotalSales
FROM
(
    SELECT
        c.CustomerName,
        SUM(od.Sales) AS TotalSales
    FROM Customers c
    JOIN Orders o
        ON c.CustomerID = o.CustomerID
    JOIN OrderDetails od
        ON o.OrderNumber = od.OrderNumber
    GROUP BY c.CustomerName
) CustomerSales
WHERE TotalSales >
(
    SELECT AVG(TotalSales)
    FROM
    (
        SELECT
            SUM(od.Sales) AS TotalSales
        FROM Customers c
        JOIN Orders o
            ON c.CustomerID = o.CustomerID
        JOIN OrderDetails od
            ON o.OrderNumber = od.OrderNumber
        GROUP BY c.CustomerID
    ) AvgSales
)
ORDER BY TotalSales DESC;



--21. PRODUCTS WITH SALES HIGHER THAN AVERAGE--

SELECT
    ProductCode,
    Sales
FROM OrderDetails
WHERE Sales >
(
    SELECT AVG(Sales)
    FROM OrderDetails
)
ORDER BY Sales DESC;



--22. ROW NUMBER FOR ORDERS BY SALES VALUE--

SELECT
    OrderNumber,
    Sales,
    ROW_NUMBER() OVER (
        ORDER BY Sales DESC
    ) AS RowNum
FROM OrderDetails;



--23. CUSTOMERS RANK BY TOTAL REVENUE--


SELECT
    c.CustomerName,
    SUM(od.Sales) AS TotalRevenue,

    RANK() OVER (
        ORDER BY SUM(od.Sales) DESC
    ) AS RevenueRank

FROM Customers c
JOIN Orders o
    ON c.CustomerID = o.CustomerID
JOIN OrderDetails od
    ON o.OrderNumber = od.OrderNumber

GROUP BY
    c.CustomerName;



--24. TOP PRODUCTS WITHIN EACH PRODUCT LINE--


SELECT
    ProductLine,
    ProductCode,
    TotalRevenue,
    ROW_NUMBER() OVER
    (
        PARTITION BY ProductLine
        ORDER BY TotalRevenue DESC
    ) AS ProductRank
FROM
(
    SELECT
        p.ProductLine,
        p.ProductCode,
        SUM(od.Sales) AS TotalRevenue
    FROM Products p
    JOIN OrderDetails od
        ON p.ProductCode = od.ProductCode
    GROUP BY
        p.ProductLine,
        p.ProductCode
) ProductSales;


--25. RANK PRODUCTS BY TOTAL QUANTITY SOLD--


SELECT
    ProductCode,
    SUM(QuantityOrdered) AS TotalQuantity,

    RANK() OVER
    (
        ORDER BY SUM(QuantityOrdered) DESC
    ) AS QuantityRank

FROM OrderDetails
GROUP BY ProductCode;



--26. LATEST ORDERS PER CUSTOMER--


SELECT
    CustomerID,
    CustomerName,
    OrderNumber,
    OrderDate
FROM
(
    SELECT
        c.CustomerID,
        c.CustomerName,
        o.OrderNumber,
        o.OrderDate,

        ROW_NUMBER() OVER
        (
            PARTITION BY c.CustomerID
            ORDER BY o.OrderDate DESC
        ) AS rn

    FROM Customers c
    JOIN Orders o
        ON c.CustomerID = o.CustomerID
) LatestOrders
WHERE rn = 1;



--27. CUSTOMERS WITH MORE THAN 5 ORDERS--


SELECT
    CustomerName,
    TotalOrders
FROM
(
    SELECT
        c.CustomerName,
        COUNT(o.OrderNumber) AS TotalOrders
    FROM Customers c
    JOIN Orders o
        ON c.CustomerID = o.CustomerID
    GROUP BY c.CustomerName
) CustomerOrders
WHERE TotalOrders > 5
ORDER BY TotalOrders DESC;



--28. RUNNING TOTAL OF MONTHLY SALES--


SELECT
    YEAR_ID,
    MONTH_ID,
    MonthlySales,

    SUM(MonthlySales) OVER
    (
        ORDER BY YEAR_ID, MONTH_ID
    ) AS RunningTotal

FROM
(
    SELECT
        o.YEAR_ID,
        o.MONTH_ID,
        SUM(od.Sales) AS MonthlySales
    FROM Orders o
    JOIN OrderDetails od
        ON o.OrderNumber = od.OrderNumber
    GROUP BY
        o.YEAR_ID,
        o.MONTH_ID
) MonthlyRevenue;


--29. TOP 10 PRODUCTS BY REVENUE--


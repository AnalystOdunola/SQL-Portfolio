--33. MONTHLY REVENUE TREND WITH YEAR ON YEAR GROWTH--


WITH MonthlySales AS (
    SELECT
        o.YEAR_ID,
        o.MONTH_ID,
        SUM(od.Sales) AS Revenue
    FROM Orders o
    JOIN OrderDetails od ON od.OrderNumber = o.OrderNumber
    GROUP BY o.YEAR_ID, o.MONTH_ID
)
SELECT
    YEAR_ID,
    MONTH_ID,
    Revenue,
    LAG(Revenue, 12) OVER (ORDER BY YEAR_ID, MONTH_ID) AS RevenueLY,
    ROUND(
        100.0 * (Revenue - LAG(Revenue, 12) OVER (ORDER BY YEAR_ID, MONTH_ID)) 
        / NULLIF(LAG(Revenue, 12) OVER (ORDER BY YEAR_ID, MONTH_ID), 0), 2
    ) AS YoY_GrowthPct,
    SUM(Revenue) OVER (PARTITION BY YEAR_ID ORDER BY MONTH_ID 
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS YTD_Revenue
FROM MonthlySales
ORDER BY YEAR_ID, MONTH_ID;



--34. MONTHLY REVENUE TREND--


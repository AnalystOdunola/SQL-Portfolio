
--1. ORDER WITH THE HIGHEST QUANTITY ORDERED--

SELECT TOP 10
    OrderNumber,
    ProductCode,
    QuantityOrdered,
    Sales
FROM OrderDetails
ORDER BY QuantityOrdered DESC;


--2. TOP 10 SALES BY ORDER NUMBER--

SELECT TOP 10
    OrderNumber,
    SUM(Sales) AS TotalSales
FROM OrderDetails
GROUP BY OrderNumber
ORDER BY TotalSales DESC;



--3. PRODUCT WITH THE HIGHEST ORDER VOLUME--


SELECT TOP 10
    ProductCode,
    SUM(QuantityOrdered) AS TotalQuantity
FROM OrderDetails
GROUP BY ProductCode
ORDER BY TotalQuantity DESC;



--4. CUSTOMER WITH THE HIGHEST NUMBER OF ORDERS--


SELECT TOP 10
    c.CustomerName,
    COUNT(o.OrderNumber) AS TotalOrders
FROM Customers c
JOIN Orders o
    ON c.CustomerID = o.CustomerID
GROUP BY c.CustomerName
ORDER BY TotalOrders DESC;



--5. TOP 10 STATES BY REVENUE GENERATED--


SELECT TOP 10
    c.State,
    SUM(od.Sales) AS TotalRevenue
FROM Customers c
JOIN Orders o
    ON c.CustomerID = o.CustomerID
JOIN OrderDetails od
    ON o.OrderNumber = od.OrderNumber
WHERE c.State IS NOT NULL
GROUP BY c.State
ORDER BY TotalRevenue DESC;




--6. TOTAL REVENUE GENERATED BY DEAL SIZE--


SELECT
    DealSize,
    SUM(Sales) AS TotalRevenue
FROM OrderDetails
GROUP BY DealSize
ORDER BY TotalRevenue DESC;



--7. TOP PRODUCT LINES BY REVENUE GENERATED--


SELECT
    p.ProductLine,
    SUM(od.Sales) AS TotalRevenue
FROM Products p
JOIN OrderDetails od
    ON p.ProductCode = od.ProductCode
GROUP BY p.ProductLine
ORDER BY TotalRevenue DESC;



--8. AVERAGE ORDER VALUE--


SELECT AVG(OrderTotal) AS AvgOrderValue
FROM (
    SELECT SUM(Sales) AS OrderTotal
    FROM OrderDetails
    GROUP BY OrderNumber
) t;


--9. CUSTOMERS WITH SALES ABOVE AVERAGE--


WITH CustomerSales AS
(
    SELECT
        c.CustomerName,
        SUM(od.Sales) AS TotalSales
    FROM Customers c
    JOIN Orders o
        ON c.CustomerID = o.CustomerID
    JOIN OrderDetails od
        ON o.OrderNumber = od.OrderNumber
    GROUP BY c.CustomerName
)

SELECT
    CustomerName,
    TotalSales
FROM CustomerSales
WHERE TotalSales >
(
    SELECT AVG(TotalSales)
    FROM CustomerSales
)
ORDER BY TotalSales DESC;



--10. MONTHLY REVENUE TREND--


SELECT
    YEAR_ID,
    MONTH_ID,
    SUM(od.Sales) AS MonthlyRevenue
FROM Orders o
JOIN OrderDetails od
    ON o.OrderNumber = od.OrderNumber
GROUP BY YEAR_ID, MONTH_ID
ORDER BY YEAR_ID, MONTH_ID;



--11. TOP 5 COUNTRIES BY SALES--



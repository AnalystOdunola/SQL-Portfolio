--40. ORDER STATUS ANALYSIS--

SELECT
    o.Status,
    COUNT(DISTINCT o.OrderNumber) AS TotalOrders,
    SUM(od.Sales) AS RevenueGenerated
FROM Orders AS o
INNER JOIN OrderDetails AS od
    ON od.OrderNumber = o.OrderNumber
GROUP BY o.Status
ORDER BY RevenueGenerated DESC;
